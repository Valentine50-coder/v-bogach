async def send_post(bot, chat_id, key, title, caption):
    files = [os.path.join(DIR, f"{key}_{i}.jpg") for i in range(1, 11)]  # 18.11: до 10 слайдів
    files = [f for f in files if os.path.exists(f)]
    if not files:
        return
    hs = [open(f, "rb") for f in files]
    try:  # 15.11: великий альбом інколи «таймаутить», хоча дійшов; опис надсилаємо все одно
        await bot.send_media_group(chat_id, [InputMediaPhoto(h) for h in hs], read_timeout=120, write_timeout=120)
    except Exception as e:
        log.warning("instapost album %s %s: %s", key, chat_id, e)
    finally:
        for h in hs:
            h.close()
    await bot.send_message(chat_id, f"📌 Карусель на сьогодні: {title}\n\nОпис 👇 (натисніть і скопіюйте)")
    await bot.send_message(chat_id, caption)


async def _to_admins(bot, key, title, caption):
    for a in C.ADMIN_IDS:
        try:
            await send_post(bot, a, key, title, caption)
        except Exception as e:
            log.warning("instapost %s %s: %s", key, a, e)


