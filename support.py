def kb():
    me = C.AUTHOR_CONTACT.lstrip("@")
    return M([[B("✍️ Записатися на супровід", url=f"https://t.me/{me}?text={quote('раціон')}")],
              [B("☰ Меню", callback_data="menu")]])


