async def job(ctx):
    if db.flag_get("vads_2311") == "1":
        return
    db.flag_set("vads_2311", "1")
    for a in C.ADMIN_IDS:
        try:
            await send(ctx.bot, a)
        except Exception as e:
            log.warning("vadsetup %s: %s", a, e)


async def cmd(update, context, is_admin):
    if not is_admin(update.effective_user.id):
        return
    await send(context.bot, update.effective_chat.id)
