T6 = 6


def cover(th, pic, tag, title, sub="", pos="center", place="bottom", n=1, total=T6):
    shade = "shade-b" if place == "bottom" else "shade-t"
    where = "bottom:90px" if place == "bottom" else "top:150px"
    return page(th, f"""<div class="full"><img src="{img(pic)}" style="object-position:{pos}"></div><div class="{shade}"></div>{top(n, total, True)}
<div style="position:absolute;left:56px;right:56px;{where};color:#fff">
  <span class="pl2">{tag}</span>
  <h1 style="margin-top:28px">{title}</h1>
  {f'<div class="p" style="margin-top:22px">{sub}</div>' if sub else ''}
</div>""")


def text(th, n, quote, paras, pic=None, picpos="center", where="top", total=T6):
    ph = (f'<div class="ph" style="left:70px;right:70px;{"bottom:90px" if where == "top" else "top:100px"};height:380px">'
          f'<img src="{img(pic)}" style="object-position:{picpos}"></div>') if pic else ""
    box = "top:130px" if where == "top" else "bottom:110px"
    q = f'<div class="quote">{quote}</div>' if quote else ""
    ps = "".join(f'<div class="p">{p}</div>' for p in paras)
    return page(th, f"""{top(n, total)}{ph}
<div style="position:absolute;left:70px;right:70px;{box}">{q}<div style="margin-top:{40 if quote else 0}px">{ps}</div></div>""")


def photo(th, n, pic, tag, paras, pos="center", total=T6):
    ps = "".join(f'<div class="p" style="font-size:37px">{p}</div>' for p in paras)
    return page(th, f"""<div class="full"><img src="{img(pic)}" style="object-position:{pos}"></div><div class="shade-b"></div>{top(n, total, True)}
<div style="position:absolute;left:56px;right:56px;bottom:90px;color:#fff"><span class="pl">{tag}</span><div style="margin-top:24px">{ps}</div></div>""")


def split(th, n, pic, tag, title, paras, side="right", pos="center", total=T6):
    ph_side = "right:56px" if side == "right" else "left:56px"
    tx_side = "left:70px" if side == "right" else "left:600px;right:56px"
    ps = "".join(f'<div class="p">{p}</div>' for p in paras)
    return page(th, f"""{top(n, total)}
<div class="ph" style="{ph_side};top:120px;width:470px;height:560px"><img src="{img(pic)}" style="object-position:{pos}"></div>
<div style="position:absolute;{tx_side};width:{470 if side == 'right' else 420}px;top:150px"><span class="pl">{tag}</span><h2 style="margin-top:24px;font-size:56px">{title}</h2></div>
<div style="position:absolute;left:70px;right:70px;top:740px">{ps}</div>""")


def cards(th, n, title, items, total=T6):
    rows = "".join(f'<div class="card" style="padding:26px 34px"><div style="font-size:36px;font-weight:800">{a}</div>'
                   f'<div class="p" style="font-size:30px;margin-top:6px">{b}</div></div>' for a, b in items)
    return page(th, f"""{top(n, total)}
<div style="position:absolute;left:70px;right:70px;top:120px"><h2>{title}</h2>
<div style="margin-top:34px;display:flex;flex-direction:column;gap:22px">{rows}</div></div>""")


def word(style, w):
    if style == "quote":
        return f'<span class="wq"><u>«{w.capitalize()}»</u></span>'
    if style == "flag":
        return f'<span class="wf">{w}</span>'
    if style == "glow":
        return f'<span class="wg">{w}</span>'
    if style == "note":
        return (f'<span style="display:inline-block;background:#fff;color:#121a3d;font-family:Lora;font-style:italic;font-size:62px;'
                f'padding:16px 34px;transform:rotate(-3deg);box-shadow:0 12px 30px rgba(0,0,0,.25)">{w.lower()}</span>')
    return f'<b style="font-size:62px;letter-spacing:4px;border:3px solid #fff;padding:10px 30px;border-radius:60px">{w}</b>'


def cta(th, n, title, paras, w, style, after, side=False, total=T6):
    ps = "".join(f'<div class="p" style="color:#e6ebff">{p}</div>' for p in paras)
    if side:
        return page(th, f"""{top(n, total, True)}<div class="ws">{w}</div>
<div style="position:absolute;left:70px;right:200px;top:220px"><h2>{title}</h2><div style="margin-top:28px">{ps}</div>
<div class="p" style="margin-top:44px">Напишіть у коментарях слово <b>{w}</b> {after}</div></div>""", "cta")
    return page(th, f"""{top(n, total, True)}
<div style="position:absolute;left:70px;right:70px;top:210px"><h2>{title}</h2><div style="margin-top:28px">{ps}</div>
<div class="p" style="margin-top:46px">Напишіть у коментарях</div><div style="margin-top:22px">{word(style, w)}</div>
<div class="p" style="margin-top:30px;color:#e6ebff">{after}</div></div>""", "cta")


