"""Звіт адмінам після кожного оновлення агента.

Як користуватися: при кожній зміні міняйте VERSION і пишіть пункти в NOTES простими словами.
Після перезапуску агент один раз надішле адмінам «Агента оновлено» з цими пунктами.
"""
import logging

import config as C
import db

log = logging.getLogger("changelog")

VERSION = "2026-11-10-1"
NOTES = [
    "Щоранку о 9:00 вам приходитиме звіт за вчора: скільки людей прийшло і звідки (сайт, діагностика, ХОЧУ, напряму), воронка від приходу до оплати, де люди зупинились, результати діагностики, оплати з іменами і «гарячі», хто взяв посилання на оплату, але не оплатив",
    "У головному меню для адмінів з'явилась кнопка «👥 CRM» (і команда /crm): групи людей (нові, пройшли діагностику, дійшли до оплати, гарячі, платять частинами, оплатили, ставили питання, заблокували), список людей з посиланнями, розсилка вибраній групі з попереднім переглядом",
    "У CRM є пошук людини за ніком, ID або ім'ям: видно, звідки прийшла і всі її кроки в агенті, а також звіти «Сьогодні» і «7 днів»",
    "Детальна статистика кроків збирається з сьогоднішнього дня. За минулі дні видно тільки, скільки людей прийшло і звідки",
]


async def send(bot):
    if db.flag_get("changelog") == VERSION:
        return
    db.flag_set("changelog", VERSION)
    text = "🔄 <b>Агента оновлено</b>\n\n" + "\n".join(f"{i}. {n}" for i, n in enumerate(NOTES, 1))
    me = await bot.get_me()
    text += (f"\n\n<b>Посилання для кодових слів:</b>\nДіагностика: https://t.me/{me.username}?start=test"
             f"\nВся інформація про інтенсив: https://t.me/{me.username}?start=hochu"
             f"\nДля кнопок сайту: https://t.me/{me.username}?start=site")
    for a in C.ADMIN_IDS:
        try:
            await bot.send_message(a, text, parse_mode="HTML")
        except Exception as e:
            log.warning("changelog %s: %s", a, e)
