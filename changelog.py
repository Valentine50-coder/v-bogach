"""Звіт адмінам після кожного оновлення агента.

Як користуватися: при кожній зміні міняйте VERSION і пишіть пункти в NOTES простими словами.
Після перезапуску агент один раз надішле адмінам «Агента оновлено» з цими пунктами.
"""
import logging

import config as C
import db

log = logging.getLogger("changelog")

VERSION = "2026-11-09-2"
NOTES = [
    "Головне меню тепер як в Ані: кнопка інтенсиву відкриває картку з фото, а під нею розділи",
    "Розділи інтенсиву окремими кнопками: Про авторку, Для кого, Програма, Що ви отримаєте, Умови і ціна",
    "У кожному розділі кнопки «Оплатити», «Назад до інтенсиву» і «Меню»",
    "Нова кнопка «Про Валентину» в головному меню",
    "Інші продукти (гайд, курс, консультації, супровід, розбір аналізів) поки відповідають «скоро»",
    "Після кожного оновлення ви отримуватимете такий звіт",
]


async def send(bot):
    if db.flag_get("changelog") == VERSION:
        return
    db.flag_set("changelog", VERSION)
    text = "🔄 <b>Агента оновлено</b>\n\n" + "\n".join(f"{i}. {n}" for i, n in enumerate(NOTES, 1))
    for a in C.ADMIN_IDS:
        try:
            await bot.send_message(a, text, parse_mode="HTML")
        except Exception as e:
            log.warning("changelog %s: %s", a, e)
