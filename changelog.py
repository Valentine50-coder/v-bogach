"""Звіт адмінам після кожного оновлення агента.

Як користуватися: при кожній зміні міняйте VERSION і пишіть пункти в NOTES простими словами.
Після перезапуску агент один раз надішле адмінам «Агента оновлено» з цими пунктами.
"""
import logging

import config as C
import db

log = logging.getLogger("changelog")

VERSION = "2026-11-13-1"
NOTES = [
    "Дожими інтенсиву всім, хто ще не оплатив: перші 3 дні активно (3, 2 і 1 повідомлення), далі раз на 2 дні, в останній день запису 3 нагадування. Тільки з 9:00 до 21:00, після оплати зупиняються. Тим, хто вже був в агенті, починаються з сьогодні",
    "Діагностика: питання повністю жирним, на картці тепер «10 простих питань, аналіз результатів та рішення від Валентини»",
    "Інтенсив тепер триває 2 тижні, спецціна до 22.11 (у всіх повідомленнях, картках і в діагностиці)",
    "Нові тексти розділів «Для кого», «Що ви отримаєте» і нова програма з 14 тем",
    "Назви розділів великими літерами, кнопка «Поставити питання» замість «Запитати у Валентини»",
    "Нова діагностика: 10 питань за новою програмою, результати посилаються на нові номери тем",
    "Оновлені картки «Про запуск» (2 тижні), «Програма» (14 тем за 14 днів) і «Умови і ціна» (до 22.11)",
]


async def send(bot):
    if db.flag_get("changelog") == VERSION:
        return
    db.flag_set("changelog", VERSION)
    text = "🔄 <b>Агента оновлено</b>\n\n" + "\n".join(f"{i}. {n}" for i, n in enumerate(NOTES, 1))
    me = await bot.get_me()
    text += (f"\n\n<b>Посилання для кодових слів:</b>\nДіагностика: https://t.me/{me.username}?start=test"
             f"\nВся інформація про інтенсив: https://t.me/{me.username}?start=hochu"
             f"\nДля кнопок сайту: https://t.me/{me.username}?start=site")
    for a in C.ADMIN_IDS:
        try:
            await bot.send_message(a, text, parse_mode="HTML")
        except Exception as e:
            log.warning("changelog %s: %s", a, e)
